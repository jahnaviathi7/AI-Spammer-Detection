from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch
from datetime import datetime
from io import BytesIO


def generate_pdf_report(
    detection_type,
    input_data,
    prediction,
    score
):

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=45,
        leftMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        textColor=colors.HexColor("#17365D"),
        alignment=TA_CENTER,
        fontSize=19
    )

    subtitle_style = ParagraphStyle(
        "Subtitle",
        parent=styles["Normal"],
        alignment=TA_CENTER,
        textColor=colors.grey
    )

    elements = []

    elements.append(
        Paragraph(
            "SPAMMER DETECTION SYSTEM",
            title_style
        )
    )

    elements.append(Spacer(1, 10))

    elements.append(
        Paragraph(
            "Fake User Identification and Spam Message Analysis",
            subtitle_style
        )
    )

    elements.append(Spacer(1, 30))

    elements.append(
        Paragraph(
            "PREDICTION REPORT",
            styles["Heading2"]
        )
    )

    elements.append(Spacer(1, 15))

    report_data = [
        ["Report Details", "Information"],
        ["Detection Type", str(detection_type)],
        ["Prediction Result", str(prediction)],
        ["Estimated Score", f"{float(score):.2%}"],
        [
            "Generated Date",
            datetime.now().strftime("%d-%m-%Y %H:%M:%S")
        ]
    ]

    table = Table(
        report_data,
        colWidths=[2.2 * inch, 3.8 * inch]
    )

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0),
         colors.HexColor("#17365D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 10),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND", (0, 1), (-1, -1),
         colors.HexColor("#F2F6FA"))
    ]))

    elements.append(table)

    elements.append(Spacer(1, 25))

    elements.append(
        Paragraph(
            "INPUT DETAILS",
            styles["Heading2"]
        )
    )

    elements.append(Spacer(1, 10))

    details = [
        ["Field", "Value"]
    ]

    if isinstance(input_data, dict):

        for key, value in input_data.items():
            details.append([str(key), str(value)])

    else:
        details.append(["Input", str(input_data)])

    detail_table = Table(
        details,
        colWidths=[2.2 * inch, 3.8 * inch]
    )

    detail_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0),
         colors.HexColor("#17365D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP")
    ]))

    elements.append(detail_table)

    elements.append(Spacer(1, 30))

    elements.append(
        Paragraph(
            "<b>Disclaimer:</b> This report contains "
            "machine-learning estimates for academic "
            "demonstration. It does not establish that "
            "an account or message is malicious. "
            "Manual review is recommended.",
            styles["Normal"]
        )
    )

    elements.append(Spacer(1, 20))

    elements.append(
        Paragraph(
            "Generated by AI Spammer Detection Project",
            subtitle_style
        )
    )

    document.build(elements)

    buffer.seek(0)

    return buffer.getvalue()